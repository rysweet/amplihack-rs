#[test]
fn a_caveat_whose_is_meta_is_not_boolean_true_is_kept() {
    let caveat = |meta: &str| {
        format!(
            r#"{{"type":"user","isMeta":{meta},"message":{{"content":"<local-command-caveat>c</local-command-caveat>"}}}}"#
        )
    };
    for meta in [r#""true""#, "1", "false", "null"] {
        assert_eq!(
            classify(&lines(&[&caveat(meta), COMMAND])),
            Verdict::Keep,
            "isMeta {meta}"
        );
    }
    let no_meta = user("<local-command-caveat>c</local-command-caveat>");
    assert_eq!(classify(&lines(&[&no_meta, COMMAND])), Verdict::Keep);
    assert_eq!(
        classify(&lines(&[&caveat("true"), COMMAND])),
        Verdict::ProbeOnly
    );
}

#[test]
fn output_entries_must_be_one_whole_element() {
    let two = user(
        "<local-command-stdout>a</local-command-stdout><local-command-stdout>b</local-command-stdout>",
    );
    assert_eq!(classify(&lines(&[COMMAND, &two])), Verdict::Keep);
    let trailing = user("<local-command-stdout>a</local-command-stdout> then a prompt");
    assert_eq!(classify(&lines(&[COMMAND, &trailing])), Verdict::Keep);
}

