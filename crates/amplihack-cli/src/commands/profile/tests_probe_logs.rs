//! `probe_logs` (issue #1974): `amplihack profile prune-probe-logs`, which
//! removes the session logs older usage probes left in the shared
//! `projects` folder, and nothing else.
//!
//! Contract:
//! - `classify(text) -> Verdict` is `ProbeOnly` only when (see
//!   docs/reference/profile-command.md, "Prune probe logs"):
//!   1. every non-empty line is a JSON object with a string `type`;
//!   2. every `type` is `user` or one of `session-owner`, `queue-operation`,
//!      `attachment`, `system`, `last-prompt`, `cost-state`; a
//!      `queue-operation` `content` or `last-prompt` `lastPrompt` field, when
//!      present, must be the string `/usage` (trimmed);
//!   3. exactly one `user` entry is the `/usage` command: string content
//!      `<command-name>/usage</command-name>`, then optionally
//!      `<command-message>usage</command-message>`, then optionally an empty
//!      `<command-args></command-args>`, whitespace only between and around;
//!   4. every other `user` entry is the caveat (`isMeta` is boolean `true`
//!      and the content is one `<local-command-caveat>` element) or one
//!      `<local-command-stdout>` / `<local-command-stderr>` element.
//!
//!   Anything else is `Keep`.
//! - `prune(dir, dry_run) -> io::Result<Pruned>` reads only regular files
//!   named `*.jsonl` directly in `dir` (no recursion, symlinks kept, files
//!   over 1 MiB kept unread). `Pruned { matched, removed, kept }`:
//!   `matched` lists the matching paths, sorted; `removed` counts files
//!   deleted (0 under `dry_run`); `kept` counts every other `.jsonl` file.
//!   A missing or unreadable `dir` is an error.
//! - `encode(home)` replaces each char outside `[A-Za-z0-9-]` with `-`;
//!   `default_dir(home) == home/.claude/projects/<encode(home)>`.
//! - `run(dir, dry_run, home, out, err) -> i32` is the subcommand: exit 0
//!   after reading the folder; 1 with no `--dir` and a `HOME` that is unset,
//!   empty or relative, or a folder that does not exist. `--dry-run` prints
//!   one quoted, escaped path per line; otherwise `removed N, kept M`. No
//!   log content is ever printed.
//!
//! Every test works in its own temp dir; `HOME` is passed in, never read.

use super::probe_logs::{Pruned, Verdict, classify, default_dir, encode, prune, run};
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};

const CAVEAT: &str = r#"{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"},"uuid":"c1"}"#;
const COMMAND: &str = r#"{"type":"user","message":{"role":"user","content":"<command-name>/usage</command-name>\n            <command-message>usage</command-message>\n            <command-args></command-args>"},"uuid":"c2"}"#;
const STDOUT: &str = r#"{"type":"user","message":{"role":"user","content":"<local-command-stdout>Current session: 37% used</local-command-stdout>"},"uuid":"c3"}"#;
const STDERR: &str = r#"{"type":"user","message":{"role":"user","content":"<local-command-stderr>boom</local-command-stderr>"},"uuid":"c4"}"#;

/// The shape of a real probe log, as documented.
fn probe_log() -> String {
    [
        r#"{"type":"session-owner","sessionId":"s"}"#,
        r#"{"type":"queue-operation","operation":"enqueue"}"#,
        r#"{"type":"attachment"}"#,
        CAVEAT,
        COMMAND,
        r#"{"type":"system","subtype":"local_command"}"#,
        r#"{"type":"last-prompt"}"#,
        r#"{"type":"cost-state"}"#,
    ]
    .join("\n")
        + "\n"
}

fn user(content: &str) -> String {
    serde_json::json!({"type": "user", "message": {"role": "user", "content": content}}).to_string()
}

fn lines(v: &[&str]) -> String {
    v.join("\n") + "\n"
}

