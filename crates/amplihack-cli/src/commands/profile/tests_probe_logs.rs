#[test]
fn the_documented_probe_log_is_probe_only() {
    assert_eq!(classify(&probe_log()), Verdict::ProbeOnly);
}

#[test]
fn a_bare_usage_command_is_probe_only() {
    assert_eq!(
        classify(&user("<command-name>/usage</command-name>")),
        Verdict::ProbeOnly
    );
    assert_eq!(
        classify(&user(
            "  <command-name>/usage</command-name>\n<command-message>usage</command-message>\n"
        )),
        Verdict::ProbeOnly
    );
}

#[test]
fn caveat_command_and_output_entries_are_probe_only() {
    assert_eq!(classify(&lines(&[CAVEAT, COMMAND])), Verdict::ProbeOnly);
    assert_eq!(
        classify(&lines(&[CAVEAT, COMMAND, STDOUT])),
        Verdict::ProbeOnly
    );
    assert_eq!(classify(&lines(&[COMMAND, STDERR])), Verdict::ProbeOnly);
}

#[test]
fn blank_lines_are_ignored() {
    assert_eq!(
        classify(&format!("\n{COMMAND}\n\n{CAVEAT}\n\n")),
        Verdict::ProbeOnly
    );
}

