struct Dir {
    _tmp: tempfile::TempDir,
    path: PathBuf,
}

fn dir() -> Dir {
    let tmp = tempfile::tempdir().unwrap();
    let path = tmp.path().canonicalize().unwrap().join("-home-someone");
    fs::create_dir_all(&path).unwrap();
    Dir { _tmp: tmp, path }
}

impl Dir {
    fn put(&self, name: &str, body: &str) -> PathBuf {
        let p = self.path.join(name);
        fs::write(&p, body).unwrap();
        p
    }

    fn names(&self) -> Vec<String> {
        let mut v: Vec<String> = fs::read_dir(&self.path)
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        v.sort();
        v
    }
}

/// One file of each kind, the matching ones named `probe-*`.
fn mixed(d: &Dir) {
    d.put("probe-a.jsonl", &probe_log());
    d.put("probe-b.jsonl", &lines(&[CAVEAT, COMMAND, STDOUT]));
    d.put(
        "probe-c.jsonl",
        &user("<command-name>/usage</command-name>"),
    );
    d.put("prompt.jsonl", &lines(&[COMMAND, &user("fix the bug")]));
    d.put("login.jsonl", &user("<command-name>/login</command-name>"));
    d.put("broken.jsonl", &lines(&[COMMAND, "{oops"]));
    // Not a `.jsonl`: never touched, never counted.
    d.put("notes.txt", &probe_log());
}

#[test]
fn prune_removes_only_probe_logs() {
    let d = dir();
    mixed(&d);
    let Pruned {
        matched,
        removed,
        kept,
    } = prune(&d.path, false).unwrap();
    assert_eq!(
        matched,
        ["probe-a.jsonl", "probe-b.jsonl", "probe-c.jsonl"]
            .map(|n| d.path.join(n))
            .to_vec()
    );
    assert_eq!((removed, kept), (3, 3));
    assert_eq!(
        d.names(),
        ["broken.jsonl", "login.jsonl", "notes.txt", "prompt.jsonl"]
    );
}

#[test]
fn a_dry_run_lists_and_removes_nothing() {
    let d = dir();
    mixed(&d);
    let before = d.names();
    let p = prune(&d.path, true).unwrap();
    assert_eq!(p.matched.len(), 3);
    assert_eq!(p.removed, 0);
    assert_eq!(d.names(), before);
}

#[test]
fn subfolders_are_not_entered() {
    let d = dir();
    let sub = d.path.join("sub");
    fs::create_dir(&sub).unwrap();
    fs::write(sub.join("probe.jsonl"), probe_log()).unwrap();
    let p = prune(&d.path, false).unwrap();
    assert!(p.matched.is_empty());
    assert!(sub.join("probe.jsonl").exists());
}

#[test]
fn a_symlinked_log_is_kept_and_its_target_untouched() {
    let d = dir();
    let outside = d._tmp.path().join("outside.jsonl");
    fs::write(&outside, probe_log()).unwrap();
    std::os::unix::fs::symlink(&outside, d.path.join("link.jsonl")).unwrap();
    let p = prune(&d.path, false).unwrap();
    assert!(p.matched.is_empty());
    assert_eq!((p.removed, p.kept), (0, 1));
    assert!(fs::symlink_metadata(d.path.join("link.jsonl")).is_ok());
    assert_eq!(fs::read_to_string(&outside).unwrap(), probe_log());
}

#[test]
fn a_file_over_one_mib_is_kept_unread() {
    let d = dir();
    let big = user(&format!(
        "<local-command-stdout>{}</local-command-stdout>",
        "x".repeat(1024 * 1024)
    ));
    let body = lines(&[COMMAND, &big]);
    // The rule alone would remove it.
    assert_eq!(classify(&body), Verdict::ProbeOnly);
    d.put("big.jsonl", &body);
    let p = prune(&d.path, false).unwrap();
    assert!(p.matched.is_empty());
    assert_eq!(p.kept, 1);
    assert!(d.path.join("big.jsonl").exists());
}

#[test]
fn a_missing_dir_is_an_error() {
    let d = dir();
    assert!(prune(&d.path.join("nope"), true).is_err());
}

// ---------------------------------------------------------------------------
// run: the subcommand
// ---------------------------------------------------------------------------

fn call(dir: Option<&Path>, dry_run: bool, home: Option<&OsStr>) -> (i32, String, String) {
    let (mut out, mut err) = (Vec::new(), Vec::new());
    let code = run(dir, dry_run, home, &mut out, &mut err);
    (
        code,
        String::from_utf8(out).unwrap(),
        String::from_utf8(err).unwrap(),
    )
}

#[test]
fn run_prints_the_counts() {
    let d = dir();
    mixed(&d);
    let (code, out, err) = call(Some(&d.path), false, None);
    assert_eq!(code, 0, "{err}");
    assert_eq!(out, "removed 3, kept 3\n");
    assert!(!d.path.join("probe-a.jsonl").exists());
}

#[test]
fn run_dry_run_prints_one_quoted_path_per_line() {
    let d = dir();
    mixed(&d);
    let (code, out, _) = call(Some(&d.path), true, None);
    assert_eq!(code, 0);
    let want: String = ["probe-a.jsonl", "probe-b.jsonl", "probe-c.jsonl"]
        .iter()
        .map(|n| format!("{:?}\n", d.path.join(n).display().to_string()))
        .collect();
    assert_eq!(out, want);
    assert!(d.path.join("probe-a.jsonl").exists());
}

#[test]
fn run_escapes_control_characters_in_paths() {
    let d = dir();
    d.put("evil\x1b[2Jname.jsonl", &probe_log());
    let (code, out, _) = call(Some(&d.path), true, None);
    assert_eq!(code, 0);
    assert!(!out.contains('\x1b'), "raw escape printed: {out:?}");
    assert!(out.contains("\\u{1b}"), "{out:?}");
}

#[test]
fn run_never_prints_log_content() {
    let d = dir();
    let secret = "SECRET-1974-CONTENT";
    d.put(
        "probe.jsonl",
        &lines(&[
            COMMAND,
            &user(&format!(
                "<local-command-stdout>{secret}</local-command-stdout>"
            )),
        ]),
    );
    d.put("prompt.jsonl", &user(secret));
    d.put("broken.jsonl", &format!("{{{secret}"));
    for dry in [true, false] {
        let (_, out, err) = call(Some(&d.path), dry, None);
        assert!(!out.contains(secret) && !err.contains(secret), "{out}{err}");
    }
}

#[test]
fn run_uses_the_encoded_home_folder_by_default() {
    let tmp = tempfile::tempdir().unwrap();
    let home = tmp.path().canonicalize().unwrap();
    let folder = default_dir(&home);
    fs::create_dir_all(&folder).unwrap();
    fs::write(folder.join("p.jsonl"), probe_log()).unwrap();
    let (code, out, err) = call(None, false, Some(home.as_os_str()));
    assert_eq!(code, 0, "{err}");
    assert_eq!(out, "removed 1, kept 0\n");
}

#[test]
fn run_needs_an_absolute_home_without_dir() {
    for home in [
        None,
        Some(OsStr::new("")),
        Some(OsStr::new("relative/home")),
    ] {
        let (code, out, err) = call(None, true, home);
        assert_eq!(code, 1, "{home:?}");
        assert!(out.is_empty());
        assert_eq!(
            err, "error: prune-probe-logs needs an absolute HOME, or --dir\n",
            "{home:?}"
        );
    }
}

#[test]
fn run_refuses_a_missing_dir() {
    let d = dir();
    let missing = d.path.join("nope");
    let (code, out, err) = call(Some(&missing), false, None);
    assert_eq!(code, 1);
    assert!(out.is_empty());
    assert_eq!(
        err,
        format!(
            "error: no such directory: {:?}\n",
            missing.display().to_string()
        )
    );
}
