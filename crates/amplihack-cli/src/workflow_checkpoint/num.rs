//! Python number text without a big-integer or float-formatting dependency:
//! `int(str)` for base 10, the per-action integer policy, and `repr(float)`.
//! Pure leaf functions, no I/O.
//!
//! The digit and whitespace tables were generated with `python3 -I` on the
//! capture host: Python 3.14.10, `unicodedata.unidata_version` 16.0.0 (760
//! Nd characters in 76 runs of ten; 25 code points `int()` strips).
//! Regenerate them, and re-run the corpus, if the 918c capture host reports
//! another unidata_version.

/// Zero code point of every run of Unicode Nd digits. Each run is ten
/// consecutive code points with decimal values 0..=9 (checked by python3
/// when generated, and by `nd_runs_are_sorted_and_ten_wide` below).
const ND_ZEROS: [u32; 76] = [
    0x30, 0x660, 0x6F0, 0x7C0, 0x966, 0x9E6, 0xA66, 0xAE6, 0xB66, 0xBE6, 0xC66, 0xCE6, 0xD66,
    0xDE6, 0xE50, 0xED0, 0xF20, 0x1040, 0x1090, 0x17E0, 0x1810, 0x1946, 0x19D0, 0x1A80, 0x1A90,
    0x1B50, 0x1BB0, 0x1C40, 0x1C50, 0xA620, 0xA8D0, 0xA900, 0xA9D0, 0xA9F0, 0xAA50, 0xABF0, 0xFF10,
    0x104A0, 0x10D30, 0x10D40, 0x11066, 0x110F0, 0x11136, 0x111D0, 0x112F0, 0x11450, 0x114D0,
    0x11650, 0x116C0, 0x116D0, 0x116DA, 0x11730, 0x118E0, 0x11950, 0x11BF0, 0x11C50, 0x11D50,
    0x11DA0, 0x11F50, 0x16130, 0x16A60, 0x16AC0, 0x16B50, 0x16D70, 0x1CCF0, 0x1D7CE, 0x1D7D8,
    0x1D7E2, 0x1D7EC, 0x1D7F6, 0x1E140, 0x1E2F0, 0x1E4F0, 0x1E5F1, 0x1E950, 0x1FBF0,
];

/// Every code point Python's `int(str)` strips as surrounding whitespace.
/// This is not `str.isspace()`: CPython maps non-ASCII whitespace to a space
/// and then strips with the C-locale `isspace`, so the ASCII separators
/// U+001C..U+001F, which `str.isspace()` accepts, make `int()` raise
/// ValueError. Generated by trying `int(c + "7" + c)` for every code point.
const INT_SPACE: [u32; 25] = [
    0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680, 0x2000, 0x2001, 0x2002, 0x2003, 0x2004,
    0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000,
];

/// CPython's default `sys.get_int_max_str_digits()`. A longer decimal
/// literal is a ValueError in the reference. Counted over digits, leading
/// zeros included and underscores excluded (checked with python3: 4301
/// zeros is refused, 4300 Nd digits are accepted).
const PY_INT_MAX_STR_DIGITS: usize = 4300;

fn int_space(c: char) -> bool {
    INT_SPACE.binary_search(&u32::from(c)).is_ok()
}

/// The decimal value of a Unicode Nd digit.
fn nd_value(c: char) -> Option<u8> {
    let cp = u32::from(c);
    let index = ND_ZEROS.partition_point(|&zero| zero <= cp);
    let zero = *ND_ZEROS.get(index.checked_sub(1)?)?;
    let offset = cp - zero;
    u8::try_from(offset).ok().filter(|v| *v < 10)
}

/// A normalised Python int: canonical decimal magnitude (no leading zeros,
/// "0" for zero) and a sign that is never negative for zero. It has no
/// arithmetic and no ordering on purpose: callers only need equality, zero
/// and the i64 range.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct PyInt {
    negative: bool,
    magnitude: String,
    /// True when every digit in the source was ASCII 0-9.
    ascii_digits: bool,
}

impl PyInt {
    pub(crate) fn fits_i64(&self) -> bool {
        self.to_i64().is_some()
    }

    /// Exact conversion; None outside i64::MIN..=i64::MAX.
    pub(crate) fn to_i64(&self) -> Option<i64> {
        let signed = if self.negative {
            format!("-{}", self.magnitude)
        } else {
            self.magnitude.clone()
        };
        signed.parse().ok()
    }

    /// Exactly `value == n` in Python, for a consumer that only compares
    /// with a small status (`rc == 2` in ORIGIN_REF_PY). No conversion is
    /// involved, so no big or negative value can wrap or saturate into `n`.
    pub(crate) fn equals_small(&self, n: u8) -> bool {
        !self.negative && self.magnitude == n.to_string()
    }
}

/// Python `int(s)` for base 10. None wherever Python raises ValueError; it
/// never yields 0 for an input Python refuses.
pub(crate) fn py_int_normalise(s: &str) -> Option<PyInt> {
    let body = s.trim_matches(int_space);
    let (negative, rest) = match body.chars().next()? {
        '-' => (true, &body[1..]),
        '+' => (false, &body[1..]),
        _ => (false, body),
    };
    let mut digits = String::with_capacity(rest.len());
    let mut ascii_digits = true;
    // Starts true so that a leading underscore is refused.
    let mut previous_was_underscore = true;
    for c in rest.chars() {
        if c == '_' {
            // One underscore, only between two digits.
            if previous_was_underscore {
                return None;
            }
            previous_was_underscore = true;
            continue;
        }
        let value = nd_value(c)?;
        ascii_digits &= c.is_ascii();
        digits.push(char::from(b'0' + value));
        previous_was_underscore = false;
    }
    if digits.is_empty() || previous_was_underscore || digits.len() > PY_INT_MAX_STR_DIGITS {
        return None;
    }
    let trimmed = digits.trim_start_matches('0');
    let magnitude = if trimmed.is_empty() {
        "0".to_owned()
    } else {
        trimmed.to_owned()
    };
    let negative = negative && magnitude != "0";
    Some(PyInt {
        negative,
        magnitude,
        ascii_digits,
    })
}

/// What each action accepts after normalisation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum IntPolicy {
    /// `after`, decision 17.138 #2: ASCII digits only, i64::MIN..=i64::MAX.
    AfterRc,
    /// `advertised-ref`, cc 00:42Z: whatever Python `int()` accepts.
    AdvertisedRc,
}

impl IntPolicy {
    pub(crate) fn admit(self, value: PyInt) -> Option<PyInt> {
        match self {
            IntPolicy::AfterRc if !value.ascii_digits || !value.fits_i64() => None,
            _ => Some(value),
        }
    }
}

/// Normalise, then apply `policy`.
pub(crate) fn py_int(text: &str, policy: IntPolicy) -> Option<PyInt> {
    py_int_normalise(text).and_then(|value| policy.admit(value))
}

/// Python's `repr(float)`, total over `f64`: `nan`, `inf` and `-inf` for the
/// non-finite values; otherwise the shortest round-trip digits, positional
/// when the decimal exponent is in -4..16, else scientific with a signed
/// exponent of at least two digits. The callers that write JSON guard
/// non-finite values themselves; this function must still never panic.
pub(crate) fn py_repr_float(value: f64) -> String {
    if value.is_nan() {
        return "nan".into();
    }
    if value.is_infinite() {
        return if value > 0.0 { "inf" } else { "-inf" }.into();
    }
    if value == 0.0 {
        return if value.is_sign_negative() {
            "-0.0"
        } else {
            "0.0"
        }
        .into();
    }
    // Rust's `{:e}` is also the shortest round-trip form: "d.ddde-x".
    let sci = format!("{value:e}");
    let (mantissa, exponent) = sci.split_once('e').unwrap_or((&sci, "0"));
    let exponent: i32 = exponent.parse().unwrap_or(0);
    let (sign, mantissa) = match mantissa.strip_prefix('-') {
        Some(rest) => ("-", rest),
        None => ("", mantissa),
    };
    let digits: String = mantissa.chars().filter(char::is_ascii_digit).collect();
    if (-4..16).contains(&exponent) {
        let point = exponent + 1;
        let body = if point <= 0 {
            format!("0.{}{digits}", "0".repeat(point.unsigned_abs() as usize))
        } else if point as usize >= digits.len() {
            format!("{digits}{}.0", "0".repeat(point as usize - digits.len()))
        } else {
            let (whole, fraction) = digits.split_at(point as usize);
            format!("{whole}.{fraction}")
        };
        format!("{sign}{body}")
    } else {
        let (first, rest) = digits.split_at(1);
        let mantissa = if rest.is_empty() {
            first.to_owned()
        } else {
            format!("{first}.{rest}")
        };
        let exp_sign = if exponent < 0 { '-' } else { '+' };
        format!("{sign}{mantissa}e{exp_sign}{:02}", exponent.unsigned_abs())
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;

    fn norm(s: &str) -> Option<String> {
        py_int_normalise(s).map(|n| {
            if n.negative {
                format!("-{}", n.magnitude)
            } else {
                n.magnitude
            }
        })
    }

    #[test]
    fn nd_runs_are_sorted_and_ten_wide() {
        assert!(ND_ZEROS.windows(2).all(|w| w[0] + 10 <= w[1]));
        assert!(INT_SPACE.windows(2).all(|w| w[0] < w[1]));
    }

    /// Each row: `python3 -I -c 'print(int(S))'` on the capture host.
    #[test]
    fn py_int_normalise_matches_python_int() {
        let accepted: &[(&str, &str)] = &[
            ("0", "0"),
            ("+0", "0"),
            ("-0", "0"),
            ("007", "7"),
            ("1_0", "10"),
            ("0_2", "2"),
            (" \u{a0} 7 ", "7"),
            ("\t79\n", "79"),
            ("\u{85}7\u{2028}", "7"),
            (" -1", "-1"),
            ("\u{663}\u{664}", "34"),
            ("\u{ff11}\u{ff12}", "12"),
            ("\u{1d7ce}", "0"),
            ("-9223372036854775808", "-9223372036854775808"),
            ("9223372036854775808", "9223372036854775808"),
            ("1234567890123456789012345", "1234567890123456789012345"),
        ];
        for (input, want) in accepted {
            assert_eq!(norm(input).as_deref(), Some(*want), "{input:?}");
        }
        assert_eq!(norm(&"0".repeat(30)).as_deref(), Some("0"));
        let refused = [
            "",
            " ",
            "+",
            "-",
            "_1",
            "1_",
            "1__0",
            "+_1",
            "- 7",
            "1 0",
            "0x10",
            "1.0",
            "1e3",
            "\u{200b}7",
            "\u{b2}",
            "++1",
            "7\u{0}",
            "x",
        ];
        for input in refused {
            assert_eq!(norm(input), None, "{input:?}");
        }
        assert_eq!(norm(&"1".repeat(4300)).map(|s| s.len()), Some(4300));
        assert_eq!(norm(&"1".repeat(4301)), None);
        assert_eq!(norm(&"0".repeat(4301)), None, "leading zeros count");
    }

    /// U+001C..U+001F: `str.isspace()` is true, but `int()` raises. Each
    /// test pairs the separator with U+0085, which `int()` does strip, so a
    /// whitespace table that dropped all non-ASCII entries would also fail.
    fn refuses_ascii_separator(sep: char) {
        assert_eq!(norm(&format!("{sep}7")), None, "{sep:?} leading");
        assert_eq!(norm(&format!("7{sep}")), None, "{sep:?} trailing");
        assert_eq!(
            norm("\u{85}7\u{85}").as_deref(),
            Some("7"),
            "U+0085 control"
        );
    }

    #[test]
    fn int_refuses_file_separator_u001c() {
        refuses_ascii_separator('\u{1c}');
    }

    #[test]
    fn int_refuses_group_separator_u001d() {
        refuses_ascii_separator('\u{1d}');
    }

    #[test]
    fn int_refuses_record_separator_u001e() {
        refuses_ascii_separator('\u{1e}');
    }

    #[test]
    fn int_refuses_unit_separator_u001f() {
        refuses_ascii_separator('\u{1f}');
    }

    #[test]
    fn after_rc_policy_is_ascii_i64_owner_17_138_2() {
        let admit = |s: &str| py_int(s, IntPolicy::AfterRc);
        assert_eq!(
            admit("-9223372036854775808").unwrap().to_i64(),
            Some(i64::MIN)
        );
        assert_eq!(
            admit("9223372036854775807").unwrap().to_i64(),
            Some(i64::MAX)
        );
        assert_eq!(admit("9223372036854775808"), None);
        assert_eq!(admit("-9223372036854775809"), None);
        assert_eq!(admit("\u{663}"), None, "non-ASCII Nd refused for after");
        assert_eq!(admit("1_0").unwrap().to_i64(), Some(10));
    }

    #[test]
    fn advertised_rc_policy_is_full_python_int_cc_0042z() {
        let admit = |s: &str| py_int(s, IntPolicy::AdvertisedRc);
        assert!(admit("\u{662}").unwrap().equals_small(2));
        assert!(admit(" 2 \n").unwrap().equals_small(2));
        assert!(admit("0_2").unwrap().equals_small(2));
        let big = admit("99999999999999999999999").unwrap();
        assert!(!big.fits_i64());
        assert!(!big.equals_small(2));
        assert!(!admit("-2").unwrap().equals_small(2));
        // 2 + 2^64 and 2 + 2^32 must not wrap to 2.
        assert!(!admit("18446744073709551618").unwrap().equals_small(2));
        assert!(!admit("4294967298").unwrap().equals_small(2));
        assert!(admit("-0").unwrap().equals_small(0));
        assert_eq!(admit("-0").unwrap().magnitude, "0");
        assert!(!admit("-0").unwrap().negative);
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod repr_float_tests {
    use super::py_repr_float;

    /// Expected values are CPython 3.14 `repr()` output. cc's 13 cases are
    /// pinned at binary level by
    /// `admission_refused_result_writes_numeric_branch_names_as_python_repr`.
    #[test]
    fn repr_matches_python_for_the_required_cases() {
        let cases: &[(f64, &str)] = &[
            (-0.0, "-0.0"),
            (0.0, "0.0"),
            (f64::NAN, "nan"),
            (f64::INFINITY, "inf"),
            (f64::NEG_INFINITY, "-inf"),
            (1e16, "1e+16"),
            (1e15, "1000000000000000.0"),
            (9_999_999_999_999_998.0, "9999999999999998.0"),
            (0.1 + 0.2, "0.30000000000000004"),
            (1.0, "1.0"),
            (100.0, "100.0"),
            (-2.5, "-2.5"),
            (1e-04, "0.0001"),
            (1e-05, "1e-05"),
            (1e-06, "1e-06"),
            (1e-07, "1e-07"),
            (1.234_567_890_123_456_8e17, "1.2345678901234568e+17"),
            (5e-324, "5e-324"),
            (f64::MAX, "1.7976931348623157e+308"),
        ];
        for (value, expected) in cases {
            assert_eq!(py_repr_float(*value), *expected, "repr({value:?})");
        }
    }

    /// Negative half: the previous code panicked at `digits.split_at(1)` for
    /// these inputs, and Rust's own spellings differ from Python's.
    #[test]
    fn non_finite_values_never_reach_the_digit_path() {
        assert_ne!(py_repr_float(f64::NAN), "NaN");
        assert_ne!(py_repr_float(f64::INFINITY), "Infinity");
        assert_ne!(py_repr_float(f64::NEG_INFINITY), "-Infinity");
    }

    /// Python's layout for one finite output: positional with a '.' when
    /// the decimal exponent is in -4..16, else `d[.ddd]e<sign><2+ digits>`
    /// with no leading zero beyond two exponent digits.
    fn assert_python_form(value: f64, text: &str) {
        let exponent = value.abs().log10().floor() as i32;
        match text.split_once('e') {
            None => {
                assert!(text.contains('.'), "{text}: positional form without '.'");
                assert!(
                    (-5..17).contains(&exponent),
                    "{text}: positional outside -4..16"
                );
            }
            Some((mantissa, exp)) => {
                let mantissa = mantissa.strip_prefix('-').unwrap_or(mantissa);
                let (lead, frac) = mantissa.split_once('.').unwrap_or((mantissa, "1"));
                assert!(lead.len() == 1 && lead != "0", "{text}: mantissa lead");
                assert!(
                    frac.bytes().all(|b| b.is_ascii_digit()) && !frac.ends_with('0'),
                    "{text}: mantissa fraction"
                );
                let digits = exp.strip_prefix(['+', '-']).expect("signed exponent");
                assert!(
                    digits.len() >= 2 && digits.bytes().all(|b| b.is_ascii_digit()),
                    "{text}: exponent digits"
                );
                assert!(
                    digits.len() == 2 || !digits.starts_with('0'),
                    "{text}: exponent padding"
                );
                let n: i32 = exp.parse().unwrap();
                assert!(!(-4..16).contains(&n), "{text}: scientific inside -4..16");
            }
        }
    }

    /// Every finite output has Python's layout and parses back to the same
    /// bits, over a fixed pseudo-random sweep of the bit space.
    #[test]
    fn finite_outputs_round_trip_bit_for_bit() {
        let mut state: u64 = 0x9E37_79B9_7F4A_7C15;
        for _ in 0..200_000 {
            state = state
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1_442_695_040_888_963_407);
            let value = f64::from_bits(state);
            if !value.is_finite() {
                continue;
            }
            let text = py_repr_float(value);
            assert_python_form(value, &text);
            let back: f64 = text.parse().unwrap();
            assert_eq!(back.to_bits(), value.to_bits(), "{text}");
        }
    }
}
